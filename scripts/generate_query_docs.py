def _slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return slug or "query"


def _query_slug(query_id: str) -> str:
    slug = _slugify(query_id)
    return f"q{slug}" if slug[:1].isdigit() else slug


def _query_label(query_id: str) -> str:
    if query_id[:1].isdigit():
        return f"Q{query_id}"
    if query_id[:1] in {"q", "Q"} and query_id[1:2].isdigit():
        return "Q" + query_id[1:]
    return query_id


def _overview_slug(benchmark_id: str) -> str:
    return _OVERVIEW_SLUG_OVERRIDES.get(benchmark_id, benchmark_id.replace("_", "-"))


_TO_BENCHMARKS = "../../"
_TO_DOCS = "../../../"
_TO_REPO = "../../../../"


def _overview_link(benchmark_id: str) -> str:
    return f"{_TO_BENCHMARKS}{_overview_slug(benchmark_id)}.md"


def _fence(code: str, lang: str) -> str:
    ticks = "```"
    while ticks in code:
        ticks += "`"
    return f"{ticks}{lang}\n{code}\n{ticks}"


def _prettify_sql(sql: str, dialect: str) -> str:
    from benchbox.utils.dialect_utils import translate_sql_query

    target = _NATIVE_SOURCE_DIALECT if dialect == "default" else dialect
    pretty = translate_sql_query(sql, target, source_dialect=target, identify=False, strict=False, pretty=True)
    return pretty if pretty.strip() else sql


def _recipe_class(benchmark_id: str) -> tuple[str, str]:
    import benchbox

    public = get_benchmark_class_name(benchmark_id)
    if public and hasattr(benchbox, public):
        return f"from benchbox import {public}", public
    core = get_core_benchmark_class_name(benchmark_id) or public or benchmark_id
    return f"from benchbox.core.{benchmark_id}.benchmark import {core}", core


_TPCDS_PARITY_DOC_URL = "https://benchbox.dev/docs/development/tpcds-dataframe-parity.html"
_TPCDS_PARITY_NOTES_URL = f"{_TPCDS_PARITY_DOC_URL}#q85-and-q93-reason-table-size"
_TPCDS_SUBSCALE_NOTES_URL = f"{_TPCDS_PARITY_DOC_URL}#q93-below-sf-1-reason-draw"


def _answer_set_note(benchmark_id: str, query_id: str) -> list[str]:
    if benchmark_id != "tpcds":
        return []
    known = TPCDS_KNOWN_DIFFERENCES.get(query_id)
    if known is None or RETURNS_DIFFERENCE not in known.classes:
        return []
    return [
        "> **Results differ from the official TPC-DS answer set.** BenchBox generates data with the official "
        "TPC-DS v4.0.0 dsdgen, whose `reason` table has 75 rows from SF 1 up. The official answer files were "
        "produced from a 35-row table and were not regenerated for v4.0.0, so this query's rows do not match them. "
        "Every platform runs on the same generated data, so results remain comparable across platforms. "
        f"See the [TPC-DS reason table notes]({_TPCDS_PARITY_NOTES_URL}).",
        "",
    ]


def _subscale_note(benchmark_id: str, query_id: str) -> list[str]:
    if benchmark_id != "tpcds" or f"query{query_id}.tpl" not in SUBSCALE_TEMPLATE_OVERRIDES:
        return []
    return [
        "> **Below SF 1 the reason is drawn from the generated rows.** dsdgen shrinks the `reason` table below "
        "SF 1 (7 rows at SF 0.1, 1 at SF 0.01), but dsqgen draws this query's reason from all 75 descriptions, "
        "so the official draw usually matches no row. Below SF 1, BenchBox draws the reason from the rows that "
        "exist at that scale, deterministically for a given seed. From SF 1 up the query text is exactly the "
        f"official one. See the [sub-SF 1 reason draw notes]({_TPCDS_SUBSCALE_NOTES_URL}).",
        "",
    ]


class DocFile:
    def __init__(self, rel_path: str, body: str) -> None:
        self.rel_path = rel_path
        self.text = "\n".join(line.rstrip() for line in body.split("\n")).rstrip() + "\n"


def _query_page(benchmark_id: str, display: str, query_id: str) -> DocFile:
    slug = _query_slug(query_id)
    label = _query_label(query_id)
    name = query_display_name(benchmark_id, query_id)
    if label == query_id and name:
        heading = f"# {display} — {name}"
    else:
        heading = f"# {display} {label}" + (f" — {name}" if name else "")

    lines = [
        _LICENSE,
        _BANNER,
        "",
        heading,
        "",
        f"```{{tags}} reference, query-template, {benchmark_id}",
        "```",
        "",
        f"> [{display}]({_overview_link(benchmark_id)}) benchmark · [all {display} queries](index.md)",
        "",
    ]

    description = query_description(benchmark_id, query_id)
    if description:
        lines += [description, ""]

    lines += _answer_set_note(benchmark_id, query_id)
    lines += _subscale_note(benchmark_id, query_id)

    render = get_sql_render(benchmark_id, query_id, bulk=True)
    lines += ["## Representative SQL", ""]
    if render is None:
        lines += ["_This query could not be rendered as standalone SQL._", ""]
    else:
        dialect = "DataFusion" if render.dialect == REFERENCE_DIALECT else render.dialect
        note = f"Rendered for **{dialect}** with default parameters."
        if render.dialect == "default":
            note = "Rendered in the benchmark's native SQL with default parameters (no dialect translation available)."
        if render.is_template:
            note += " Parameter placeholders are shown literally."
        lines += [note, "", _fence(_prettify_sql(render.sql, render.dialect), "sql"), ""]

    df_render = get_dataframe_render(benchmark_id, query_id)
    lines += ["## Representative DataFrame", ""]
    if df_render is None:
        lines += ["_No DataFrame implementation is registered for this query._", ""]
    else:
        family = {"expression": "Expression family (Polars, PySpark, DataFusion)", "pandas": "Pandas family"}.get(
            df_render.family, df_render.family
        )
        lines += [f"{family}, default parameters.", "", _fence(df_render.source, "python"), ""]

    lines += ["## Get the exact query for your run", ""]
    lines += [
        "The blocks above are representative. To get the precise statement a "
        "specific platform runs at a specific scale, substitute your own values:",
        "",
    ]
    scale = get_benchmark_default_scale(benchmark_id)
    import_line, class_name = _recipe_class(benchmark_id)
    key = native_query_key(benchmark_id, query_id)
    if supports_dialect_translation(benchmark_id):
        sql_recipe = (
            f"{import_line}\n\n"
            f"bench = {class_name}(scale_factor={scale})            # your scale factor\n"
            f'queries = bench.get_queries(dialect="{REFERENCE_DIALECT}")   # your platform\'s dialect; '
            f"drop dialect= for native SQL\n"
            f"print(queries[{key!r}])"
        )
    else:
        sql_recipe = (
            f"{import_line}\n\n"
            f"bench = {class_name}(scale_factor={scale})            # your scale factor\n"
            f"print(bench.get_queries()[{key!r}])"
        )
    lines += [_fence(sql_recipe, "python"), ""]

    if benchmark_id in _SEED_DRIVEN and query_id.isdigit():
        lines += [
            "Parameter substitution for this benchmark is seed-driven; pass a "
            "`seed` for a specific stream's parameters:",
            "",
            _fence(
                f'print(bench.get_query({query_id}, scale_factor={scale}, seed=42, dialect="{REFERENCE_DIALECT}"))',
                "python",
            ),
            "",
        ]

    if df_render is not None:
        df_recipe = (
            "from benchbox.core.query_catalog import get_dataframe_render\n\n"
            f'print(get_dataframe_render({benchmark_id!r}, {query_id!r}, family="expression").source)'
            '  # or family="pandas"'
        )
        lines += ["For the DataFrame form:", "", _fence(df_recipe, "python"), ""]

    source = query_source_path(benchmark_id, query_id)
    if source:
        lines += ["## Source", "", f"Query text: [`{source}`]({_TO_REPO}{source})", ""]

    return DocFile(f"{benchmark_id}/{slug}.md", "\n".join(lines))


def _catalog_table(benchmark_id: str, query_ids: list[str]) -> list[str]:
    rows = ["| Query | Name |", "|---|---|"]
    for query_id in query_ids:
        name = (query_display_name(benchmark_id, query_id) or "").replace("|", "\\|")
        rows.append(f"| [{_query_label(query_id)}]({_query_slug(query_id)}.md) | {name} |")
    return rows


def _grouping(benchmark_id: str, query_ids: list[str]) -> dict[str, list[str]] | None:
    if len(query_ids) <= _GROUP_THRESHOLD:
        return None
    groups = query_groups(benchmark_id)
    if groups:
        return groups
    buckets: dict[str, list[str]] = {}
    for start in range(0, len(query_ids), _BUCKET_SIZE):
        chunk = query_ids[start : start + _BUCKET_SIZE]
        buckets[f"queries {start + 1}-{start + len(chunk)}"] = chunk
    return buckets


def _benchmark_files(benchmark_id: str, display: str) -> list[DocFile]:
    query_ids = list_query_ids(benchmark_id)
    files = [_query_page(benchmark_id, display, qid) for qid in query_ids]

    groups = _grouping(benchmark_id, query_ids)
    header = [
        _LICENSE,
        _BANNER,
        "",
        f"# {display} Query Templates",
        "",
        f"```{{tags}} reference, query-template, {benchmark_id}",
        "```",
        "",
        f"> [{display} overview]({_overview_link(benchmark_id)})",
        "",
        f"Representative SQL and DataFrame renderings for each of the "
        f"{len(query_ids)} {display} queries. Every page also shows how to extract "
        f"the exact query for a given platform and scale.",
        "",
    ]
    if benchmark_id in _TPC_DERIVED:
        header += [_TPC_NOTICE, ""]

    if groups is None:
        body = header + _catalog_table(benchmark_id, query_ids)
        body += ["", "```{toctree}", ":hidden:", ""]
        body += [_query_slug(qid) for qid in query_ids]
        body += ["```"]
        files.append(DocFile(f"{benchmark_id}/index.md", "\n".join(body)))
        return files

    body = header + ["## Query groups", ""]
    for group_name in groups:
        group_slug = _slugify(group_name)
        body.append(f"- [{group_name}](group-{group_slug}.md) ({len(groups[group_name])})")
    body += ["", "```{toctree}", ":hidden:", ""]
    body += [f"group-{_slugify(g)}" for g in groups]
    body += ["```"]
    files.append(DocFile(f"{benchmark_id}/index.md", "\n".join(body)))

    for group_name, group_ids in groups.items():
        group_slug = _slugify(group_name)
        gbody = [
            _LICENSE,
            _BANNER,
            "",
            f"# {display} Query Templates — {group_name}",
            "",
            f"```{{tags}} reference, query-template, {benchmark_id}",
            "```",
            "",
            f"> [All {display} query groups](index.md)",
            "",
        ]
        gbody += _catalog_table(benchmark_id, group_ids)
        gbody += ["", "```{toctree}", ":hidden:", ""]
        gbody += [_query_slug(qid) for qid in group_ids]
        gbody += ["```"]
        files.append(DocFile(f"{benchmark_id}/group-{group_slug}.md", "\n".join(gbody)))

    return files


def _top_index(benchmark_rows: list[tuple[str, str, int]]) -> DocFile:
    lines = [
        _LICENSE,
        _BANNER,
        "",
        "# Query Templates",
        "",
        "```{tags} reference, query-template",
        "```",
        "",
        "Representative SQL and DataFrame renderings for every query in every "
        "BenchBox benchmark, one page per query. Each page shows a DataFusion "
        "rendering with default parameters and a short recipe for extracting the "
        "exact query a specific platform runs at a specific scale.",
        "",
        "| Benchmark | Queries |",
        "|---|---|",
    ]
    for benchmark_id, display, count in benchmark_rows:
        lines.append(f"| [{display}]({benchmark_id}/index.md) | {count} |")
    lines += ["", "```{toctree}", ":hidden:", ""]
    lines += [f"{benchmark_id}/index" for benchmark_id, _, _ in benchmark_rows]
    lines += ["```"]
    return DocFile("index.md", "\n".join(lines))


def render_all(benchmarks: set[str] | None = None) -> dict[str, str]:
    out: dict[str, str] = {}
    rows: list[tuple[str, str, int]] = []
    for benchmark_id, meta in sorted(get_all_benchmarks().items()):
        if get_benchmark_surface(benchmark_id) != "public":
            continue
        if benchmarks is not None and benchmark_id not in benchmarks:
            continue
        query_ids = list_query_ids(benchmark_id)
        if not query_ids:
            continue
        display = meta.get("display_name", benchmark_id)
        rows.append((benchmark_id, display, len(query_ids)))
        for doc in _benchmark_files(benchmark_id, display):
            out[doc.rel_path] = doc.text
    top = _top_index(rows)
    out[top.rel_path] = top.text
    return out


def _on_disk(root: Path) -> dict[str, str]:
    if not root.exists():
        return {}
    return {path.relative_to(root).as_posix(): path.read_text(encoding="utf-8") for path in root.rglob("*.md")}


def check_tree(rendered: dict[str, str], root: Path) -> int:
    existing = _on_disk(root)
    drift = []
    for rel in sorted(set(rendered) | set(existing)):
        want, have = rendered.get(rel), existing.get(rel)
        if want == have:
            continue
        if want is None:
            drift.append(f"  {rel}: on disk but not generated (delete it)")
        elif have is None:
            drift.append(f"  {rel}: generated but missing on disk")
        else:
            patch = "".join(
                difflib.unified_diff(
                    have.splitlines(keepends=True),
                    want.splitlines(keepends=True),
                    fromfile=f"{rel} (committed)",
                    tofile=f"{rel} (regenerated)",
                )
            )
            drift.append(f"  {rel}: content drift\n{patch}")
    if drift:
        sys.stderr.write(
            "query docs are out of date - run `uv run scripts/generate_query_docs.py`\n" + "\n".join(drift) + "\n"
        )
        return 1
    print(f"query docs match the catalog ({len(rendered)} files)")
    return 0


def write_tree(rendered: dict[str, str], root: Path) -> None:
    for rel in sorted(set(_on_disk(root)) - set(rendered)):
        (root / rel).unlink()
    for rel, text in sorted(rendered.items()):
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    for path in sorted(root.glob("*")):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=CLI_DESCRIPTION)
    parser.add_argument("--check", action="store_true", help="Exit non-zero if the on-disk tree is stale.")
    args = parser.parse_args(argv)

    rendered = render_all()
    if args.check:
        return check_tree(rendered, QUERIES_DIR)
    write_tree(rendered, QUERIES_DIR)
    print(f"wrote {len(rendered)} files under {QUERIES_DIR.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
