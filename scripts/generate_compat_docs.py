from __future__ import annotations

import argparse
import difflib
import importlib
import pkgutil
import sys
from collections import defaultdict
from pathlib import Path

import benchbox.sql_compat.rules as _rules_pkg
from benchbox.sql_compat.context import Phase
from benchbox.sql_compat.decision import CompatibilityDecision, SupportLevel
from benchbox.sql_compat.registry import REGISTRY

CLI_DESCRIPTION = "Generate sql_compat capability matrix and skip reference from the registry."

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = REPO_ROOT / "docs" / "compat"
CAPABILITY_MATRIX_PATH = DOCS_DIR / "capability-matrix.md"
SKIP_REFERENCE_PATH = DOCS_DIR / "skip-reference.md"

_BANNER = (
    "<!-- AUTOGENERATED by scripts/generate_compat_docs.py from "
    "benchbox/sql_compat/rules/. Do not edit by hand. Run "
    "`uv run scripts/generate_compat_docs.py` to refresh. -->"
)

_PHASE_ORDER = [phase.value for phase in Phase]


def _load_all_rules() -> None:
    failed: list[str] = []
    for _, mod_name, ispkg in pkgutil.walk_packages(_rules_pkg.__path__, _rules_pkg.__name__ + "."):
        if ispkg:
            continue
        try:
            importlib.import_module(mod_name)
        except Exception as exc:
            failed.append(f"{mod_name}: {exc}")
    if failed:
        raise RuntimeError(
            "Cannot generate compat docs - failed to import rule module(s):\n" + "\n".join(f"  {m}" for m in failed)
        )


def _scope_label(benchmark: str | None, query_id: str | None) -> str:
    if benchmark is None and query_id is None:
        return "platform-wide"
    if query_id is None:
        return f"benchmark={benchmark}"
    return f"benchmark={benchmark}, query={query_id}"


def _rule_rows() -> list[tuple[str, str, str, str, str, str, str, str]]:
    rows: list[tuple[str, str, str, str, str, str, str, str]] = []
    for (phase, platform, benchmark, query_id), entry in REGISTRY.all_rules():
        decision: CompatibilityDecision = entry.decision
        rows.append(
            (
                platform,
                phase.value,
                _scope_label(benchmark, query_id),
                decision.action.value,
                decision.support_level.value,
                decision.failure_mode.value,
                decision.rule_id,
                decision.reason,
            )
        )
    rows.sort(
        key=lambda r: (
            r[0],
            _PHASE_ORDER.index(r[1]) if r[1] in _PHASE_ORDER else len(_PHASE_ORDER),
            r[2],
            r[6],
        )
    )
    return rows


def _render_capability_matrix(rows: list[tuple[str, str, str, str, str, str, str, str]]) -> str:
    by_platform: dict[str, list[tuple[str, str, str, str, str, str, str, str]]] = defaultdict(list)
    for row in rows:
        by_platform[row[0]].append(row)

    summary_counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for row in rows:
        summary_counts[row[0]][row[1]] += 1

    lines: list[str] = [
        _BANNER,
        "",
        "# SQL Compatibility Capability Matrix",
        "",
        (
            "Every rule registered in `benchbox.sql_compat` is listed below. The "
            "registry is the authoritative source of compatibility policy; this "
            "document is regenerated from it. See "
            "[adr-sql-compat-phase-aware-pipeline.md](../development/adr/adr-sql-compat-phase-aware-pipeline.md) "
            "for the design."
        ),
        "",
        f"**Total registered rules:** {len(rows)}",
        "",
        f"**Platforms covered:** {len(by_platform)}",
        "",
        "## Phase coverage by platform",
        "",
    ]

    phases_present = sorted({row[1] for row in rows}, key=lambda p: _PHASE_ORDER.index(p))
    header = ["platform", *phases_present, "total"]
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "|".join(["---"] * len(header)) + "|")
    for platform in sorted(by_platform):
        counts = summary_counts[platform]
        cells = [platform]
        for phase in phases_present:
            cells.append(str(counts.get(phase, 0)) if counts.get(phase, 0) else "-")
        cells.append(str(sum(counts.values())))
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")

    lines.append("## Rules by platform")
    lines.append("")
    for platform in sorted(by_platform):
        lines.append(f"### {platform}")
        lines.append("")
        lines.append("| phase | scope | action | support | failure mode | rule_id |")
        lines.append("|---|---|---|---|---|---|")
        for row in by_platform[platform]:
            _, phase, scope, action, support, failure, rule_id, _ = row
            lines.append(f"| {phase} | {scope} | {action} | {support} | {failure} | `{rule_id}` |")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _render_skip_reference(rows: list[tuple[str, str, str, str, str, str, str, str]]) -> str:
    will_not_run_levels = {SupportLevel.BLOCKED.value, SupportLevel.SKIPPED_QUERY.value}
    runs_with_caveats_levels = {SupportLevel.SKIPPED_DDL_FRAGMENT.value, SupportLevel.INFORMATIONAL.value}
    all_skip_levels = will_not_run_levels | runs_with_caveats_levels

    skip_rows = [r for r in rows if r[4] in all_skip_levels]
    will_not_run_rows = [r for r in skip_rows if r[4] in will_not_run_levels]
    caveats_rows = [r for r in skip_rows if r[4] in runs_with_caveats_levels]

    all_platforms = {r[0] for r in skip_rows}

    lines: list[str] = [
        _BANNER,
        "",
        "# SQL Compatibility Skip Reference",
        "",
        (
            "Rules the registry applies to queries, benchmarks, and DDL statements. "
            "Split into two sections based on whether the outcome is user-visible in "
            "result counts. Each entry names the platform, the scope the rule applies "
            "to, the registered reason, and the rule_id you can grep for in "
            "`benchbox/sql_compat/rules/`."
        ),
        "",
        f"**Total rules:** {len(skip_rows)}",
        "",
        f"**Platforms with rules:** {len(all_platforms)}",
        "",
    ]

    if not skip_rows:
        lines.extend(["_No BLOCKED, SKIPPED_QUERY, SKIPPED_DDL_FRAGMENT, or INFORMATIONAL rules are registered._", ""])
        return "\n".join(lines).rstrip() + "\n"

    lines.extend(
        [
            "## Will not run",
            "",
            "Queries or benchmarks that are **omitted from the result set** - either because the "
            "benchmark is refused at preflight (BLOCKED) or a specific query is excluded from "
            "execution (SKIPPED_QUERY). Users see these as missing entries in result counts.",
            "",
        ]
    )

    if will_not_run_rows:
        by_platform: dict[str, list] = defaultdict(list)
        for row in will_not_run_rows:
            by_platform[row[0]].append(row)
        for platform in sorted(by_platform):
            lines.append(f"### {platform}")
            lines.append("")
            lines.append("| support | scope | phase | reason | rule_id |")
            lines.append("|---|---|---|---|---|")
            for row in by_platform[platform]:
                _, phase, scope, _action, support, _failure, rule_id, reason = row
                reason_cell = reason.replace("|", "\\|").replace("\n", " ").strip()
                lines.append(f"| {support} | {scope} | {phase} | {reason_cell} | `{rule_id}` |")
            lines.append("")
    else:
        lines.extend(["_No BLOCKED or SKIPPED_QUERY rules are registered._", ""])

    lines.extend(
        [
            "## Runs with caveats",
            "",
            "Benchmarks that **run end-to-end** but with documented internal gaps - either an "
            "auxiliary DDL statement is suppressed (SKIPPED_DDL_FRAGMENT) or a platform-level "
            "semantic guarantee is not enforced (INFORMATIONAL). Result counts are not affected; "
            "the caveat is noted for audit purposes.",
            "",
        ]
    )

    if caveats_rows:
        by_platform2: dict[str, list] = defaultdict(list)
        for row in caveats_rows:
            by_platform2[row[0]].append(row)
        for platform in sorted(by_platform2):
            lines.append(f"### {platform}")
            lines.append("")
            lines.append("| support | scope | phase | reason | rule_id |")
            lines.append("|---|---|---|---|---|")
            for row in by_platform2[platform]:
                _, phase, scope, _action, support, _failure, rule_id, reason = row
                reason_cell = reason.replace("|", "\\|").replace("\n", " ").strip()
                lines.append(f"| {support} | {scope} | {phase} | {reason_cell} | `{rule_id}` |")
            lines.append("")
    else:
        lines.extend(["_No SKIPPED_DDL_FRAGMENT or INFORMATIONAL rules are registered._", ""])

    return "\n".join(lines).rstrip() + "\n"


def _render_all() -> dict[Path, str]:
    rows = _rule_rows()
    return {
        CAPABILITY_MATRIX_PATH: _render_capability_matrix(rows),
        SKIP_REFERENCE_PATH: _render_skip_reference(rows),
    }


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _diff(path: Path, expected: str) -> str:
    actual = path.read_text(encoding="utf-8") if path.exists() else ""
    if actual == expected:
        return ""
    return "".join(
        difflib.unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=f"{path} (committed)",
            tofile=f"{path} (regenerated)",
        )
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=CLI_DESCRIPTION)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify the on-disk docs match the registry; exit non-zero on drift.",
    )
    args = parser.parse_args(argv)

    _load_all_rules()
    rendered = _render_all()

    if args.check:
        diffs = {path: _diff(path, content) for path, content in rendered.items()}
        drift = {path: d for path, d in diffs.items() if d}
        if drift:
            sys.stderr.write("compat docs are out of date - run `uv run scripts/generate_compat_docs.py`\n")
            for path, patch in drift.items():
                sys.stderr.write(f"\n--- drift in {path.relative_to(REPO_ROOT)} ---\n")
                sys.stderr.write(patch)
            return 1
        print("compat docs match registry")
        return 0

    for path, content in rendered.items():
        _write(path, content)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
