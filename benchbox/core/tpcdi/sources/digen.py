BENCHMARK_ID = "tpcdi"
PROVIDER = "digen"
TOOL_NAME = "DIGen"

SUPPORTED_JAVA_MAJORS = (8,)

JAVA_HOME_ENVIRONMENT = ("BENCHBOX_JAVA_HOME", "JAVA_HOME")
JAVA_OPTS_ENVIRONMENT = "BENCHBOX_TPCDI_JAVA_OPTS"

LICENCE_NOTICE = (
    "TPC-DI data is generated by the TPC's DIGen tool, which includes bankmark's PDGF. "
    "Read the licence conditions in {path}."
)
JAVA_REQUIREMENT_MESSAGE = (
    "TPC-DI data generation needs Java {versions}. Set JAVA_HOME or put a supported java on PATH. Found: {found}."
)

REPORT_NAME = "digen_report.txt"
BATCH_DATE_FILE = "BatchDate.txt"
_ACTION_TAG = "{http://www.tpc.org/tpc-di}Action"
REQUIRED_ENTRIES = ("Batch1", "Batch2", "Batch3", REPORT_NAME)
LICENCE_ANSWER = b"\nYES\n"
JAVA_PROBE_SECONDS = 10
OUTPUT_TAIL_CHARACTERS = 4000

_BATCH_ROW_COUNT = re.compile(r"TotalRecords for Batch([123]): (\d+)")
_REPORT_SCALE = re.compile(r"^Scale Factor: (\d+)\s*$", re.MULTILINE)
_REPORT_DIGEN_VERSION = re.compile(r"^DIGen Version: (\S+)\s*$", re.MULTILINE)
_REPORT_PDGF_VERSION = re.compile(r"^PDGF Version: (.+?)\s*$", re.MULTILINE)
_REPORT_VOLATILE_LINE = re.compile(r"^(Start Time|End Time|Command options used|Java version):")
_REPORT_THROUGHPUT = re.compile(r"(TotalRecords all Batches: \d+) .*$")
_JAVA_VERSION = re.compile(r'version "(\d+)(?:\.(\d+))?')
_FINWIRE_QUARTER = re.compile(r"^FINWIRE\d{4}Q[1-4]")
_HASH_CHUNK_BYTES = 1 << 20
_DEADLINE_CHECK_ACTIONS = 4096


class DigenError(RuntimeError):
    pass


class DigenJavaError(DigenError):
    pass


class DigenRunError(DigenError):
    pass


class DigenOutputError(DigenError):
    pass


class StagingTamperedError(DigenError):
    pass


@dataclass(frozen=True)
class JavaRuntime:
    executable: Path
    major: int | None

    def describe(self) -> str:
        if self.major is None:
            return f"unreadable version at {self.executable}"
        return f"Java {self.major} at {self.executable}"


@dataclass(frozen=True)
class DigenReport:
    digen_version: str
    pdgf_version: str
    scale_factor: int
    historical_rows: int
    incremental_1_rows: int
    incremental_2_rows: int
    normalised: str

    @property
    def row_counts(self) -> dict[str, int]:
        return {
            "historical": self.historical_rows,
            "incremental_1": self.incremental_1_rows,
            "incremental_2": self.incremental_2_rows,
        }


@dataclass(frozen=True)
class DigenResult:
    output_dir: Path
    scale_factor: int
    manifest_path: Path
    manifest_hash: str
    row_counts: dict[str, int]
    digen_version: str
    pdgf_version: str
    tools_sha256: str
    java_major: int | None
    java_executable: str | None
    licence_notice_shown: bool
    licence_notice: str | None
    file_count: int
    size_bytes: int
    seconds: float
    reused: bool

    def as_record(self) -> dict[str, Any]:
        return {
            "provider": PROVIDER,
            "scale_factor": self.scale_factor,
            "output_dir": str(self.output_dir),
            "manifest_path": str(self.manifest_path),
            "manifest_hash": self.manifest_hash,
            "row_counts": dict(self.row_counts),
            "digen_version": self.digen_version,
            "pdgf_version": self.pdgf_version,
            "tools_sha256": self.tools_sha256,
            "java_major": self.java_major,
            "licence_notice_shown": self.licence_notice_shown,
            "file_count": self.file_count,
            "size_bytes": self.size_bytes,
            "seconds": self.seconds,
            "reused": self.reused,
        }


def licence_notice() -> str:
    return LICENCE_NOTICE.format(path=TOOLS_ARCHIVE_PATH.parent)


def print_licence_notice() -> str:
    notice = licence_notice()
    get_console(quiet=False).print(notice, soft_wrap=True, markup=False, highlight=False)
    return notice


def probe_java_major(executable: Path) -> int | None:
    deadline = current_run_deadline()
    limit = {} if deadline is not None else {"timeout": JAVA_PROBE_SECONDS}
    try:
        completed = run_child(
            [str(executable), "-version"], tool="java", deadline=deadline, capture_output=True, text=True, **limit
        )
    except (OSError, subprocess.SubprocessError):
        return None
    match = _JAVA_VERSION.search(f"{completed.stderr}\n{completed.stdout}")
    if match is None:
        return None
    major = int(match.group(1))
    if major == 1 and match.group(2) is not None:
        return int(match.group(2))
    return major


def _java_candidates(environ: Mapping[str, str]) -> Iterator[Path]:
    locations = [str(Path(home) / "bin") for name in JAVA_HOME_ENVIRONMENT if (home := environ.get(name))]
    locations.append(environ.get("PATH"))
    seen: set[Path] = set()
    for location in locations:
        found = shutil.which("java", path=location)
        if found is None:
            continue
        candidate = Path(found)
        key = candidate.resolve()
        if key not in seen:
            seen.add(key)
            yield candidate


def find_supported_java(environ: Mapping[str, str] | None = None) -> JavaRuntime:
    found: list[JavaRuntime] = []
    for candidate in _java_candidates(os.environ if environ is None else environ):
        runtime = JavaRuntime(candidate, probe_java_major(candidate))
        if runtime.major in SUPPORTED_JAVA_MAJORS:
            return runtime
        found.append(runtime)
    raise DigenJavaError(
        JAVA_REQUIREMENT_MESSAGE.format(
            versions=" or ".join(str(major) for major in SUPPORTED_JAVA_MAJORS),
            found=", ".join(runtime.describe() for runtime in found) if found else "no java",
        )
    )


def parse_report(text: str) -> DigenReport:
    counts = {int(batch): int(rows) for batch, rows in _BATCH_ROW_COUNT.findall(text)}
    scale = _REPORT_SCALE.search(text)
    version = _REPORT_DIGEN_VERSION.search(text)
    pdgf = _REPORT_PDGF_VERSION.search(text)
    if set(counts) != {1, 2, 3} or scale is None or version is None or pdgf is None:
        raise DigenOutputError(
            f"{REPORT_NAME} does not state the DIGen version, the PDGF version, the scale factor and the row counts "
            "of Batch1, Batch2 and Batch3"
        )
    return DigenReport(
        digen_version=version.group(1),
        pdgf_version=pdgf.group(1),
        scale_factor=int(scale.group(1)),
        historical_rows=counts[1],
        incremental_1_rows=counts[2],
        incremental_2_rows=counts[3],
        normalised=normalise_report(text),
    )


def normalise_report(text: str) -> str:
    lines = [
        _REPORT_THROUGHPUT.sub(r"\1", line.rstrip())
        for line in text.splitlines()
        if line.strip() and not _REPORT_VOLATILE_LINE.match(line)
    ]
    return "\n".join(lines)


def _table_name(file_name: str) -> str:
    stem = file_name.removesuffix(".csv") if file_name.endswith("_audit.csv") else Path(file_name).stem
    if _FINWIRE_QUARTER.match(stem):
        return "FINWIRE_audit" if stem.endswith("_audit") else "FINWIRE"
    return stem


def _file_format(file_name: str) -> str:
    return Path(file_name).suffix.lstrip(".") or "text"


def _check_deadline() -> None:
    deadline = current_run_deadline()
    if deadline is not None:
        deadline.check()


def _count_actions(path: Path) -> int:
    count = 0
    root = None
    try:
        for event, element in ElementTree.iterparse(path, events=("start", "end")):
            if root is None:
                root = element
            if event == "end" and element.tag == _ACTION_TAG:
                count += 1
                root.clear()
                if count % _DEADLINE_CHECK_ACTIONS == 0:
                    _check_deadline()
    except ElementTree.ParseError as error:
        raise DigenOutputError(f"{path} is not well-formed XML: {error}") from None
    return count


def check_payload(output_dir: Path, report: DigenReport, records: Mapping[str, int]) -> None:
    expected = {
        "Batch1": report.historical_rows,
        "Batch2": report.incremental_1_rows,
        "Batch3": report.incremental_2_rows,
    }
    for name, rows in expected.items():
        batch_dir = output_dir / name
        payload = (
            [path for path in sorted(batch_dir.iterdir()) if path.is_file() and not path.name.endswith("_audit.csv")]
            if batch_dir.is_dir()
            else []
        )
        if (
            BATCH_DATE_FILE not in {path.name for path in payload}
            or len(payload) < 2
            or any(path.stat().st_size == 0 for path in payload)
        ):
            raise DigenOutputError(f"{name} in {output_dir} does not hold the data files DIGen writes")
        total = sum(records[f"{name}/{path.name}"] for path in payload if path.name != BATCH_DATE_FILE)
        if total != rows:
            raise DigenOutputError(f"{name} in {output_dir} holds {total} records but {REPORT_NAME} states {rows}")


def _digest_file(path: Path, *, is_report: bool) -> tuple[str, int, int]:
    _check_deadline()
    if is_report:
        text = path.read_text(encoding="utf-8", errors="replace")
        normalised = normalise_report(text).encode("utf-8")
        return hashlib.sha256(normalised).hexdigest(), path.stat().st_size, len(text.splitlines())
    digest = hashlib.sha256()
    newlines = 0
    size = 0
    last = b"\n"
    with path.open("rb") as stream:
        while chunk := stream.read(_HASH_CHUNK_BYTES):
            _check_deadline()
            digest.update(chunk)
            newlines += chunk.count(b"\n")
            size += len(chunk)
            last = chunk[-1:]
    lines = newlines + (0 if last == b"\n" else 1)
    if path.suffix == ".xml":
        records = _count_actions(path)
    elif path.name.endswith("_audit.csv"):
        records = max(lines - 1, 0)
    else:
        records = lines
    return digest.hexdigest(), size, records


def _staging_files(output_dir: Path) -> list[Path]:
    ignored = {MANIFEST_FILENAME, GENERATION_IN_PROGRESS_MARKER}
    return sorted(
        (path for path in output_dir.rglob("*") if path.is_file() and path.name not in ignored),
        key=lambda path: path.relative_to(output_dir).as_posix(),
    )


def _identity(scale_factor: int, files: list[tuple[str, int, str, int]], row_counts: Mapping[str, int]) -> str:
    payload = {
        "benchmark": BENCHMARK_ID,
        "scale_factor": scale_factor,
        "tools_sha256": TOOLS_ARCHIVE_SHA256,
        "row_counts": dict(row_counts),
        "files": [list(entry) for entry in files],
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def datagen_cache_key(scale_factor: Any) -> str:
    payload = {
        "benchmark": BENCHMARK_ID,
        "provider": PROVIDER,
        "scale_factor": validate_digen_scale(scale_factor),
        "tools_sha256": TOOLS_ARCHIVE_SHA256,
        "data_generation_version": DATA_GENERATION_VERSION,
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()


def write_staging_manifest(
    output_dir: Path,
    report: DigenReport,
    *,
    java: JavaRuntime | None,
    licence_notice_shown: bool,
    licence_notice_text: str | None,
) -> tuple[Path, str, int, int]:
    entries: list[tuple[Path, str, int, int]] = []
    listed: list[tuple[str, int, str, int]] = []
    size_bytes = 0
    for path in _staging_files(output_dir):
        relative = path.relative_to(output_dir).as_posix()
        checksum, size, lines = _digest_file(path, is_report=relative == REPORT_NAME)
        entries.append((path, checksum, size, lines))
        listed.append((relative, 0 if relative == REPORT_NAME else size, checksum, lines))
        size_bytes += size
    check_payload(output_dir, report, {path.relative_to(output_dir).as_posix(): rows for path, _, _, rows in entries})
    manifest_hash = _identity(report.scale_factor, listed, report.row_counts)
    manifest = DataGenerationManifest(
        output_dir=output_dir,
        benchmark=BENCHMARK_ID,
        scale_factor=report.scale_factor,
        formats=["csv"],
        stamp=False,
        extra_metadata={
            "manifest_hash": manifest_hash,
            "source": {
                "provider": PROVIDER,
                "data_generation_version": DATA_GENERATION_VERSION,
                "digen_version": report.digen_version,
                "pdgf_version": report.pdgf_version,
                "tools_sha256": TOOLS_ARCHIVE_SHA256,
                "row_counts": report.row_counts,
                "java_major": None if java is None else java.major,
                "licence_notice_shown": licence_notice_shown,
                "licence_notice": licence_notice_text,
                "report_checksum_basis": "normalised",
            },
        },
    )
    for path, checksum, size, records in entries:
        relative = path.relative_to(output_dir)
        batch = relative.parts[0] if relative.parts[0].startswith("Batch") and len(relative.parts) > 1 else None
        manifest.add_entry(
            _table_name(path.name),
            path,
            row_count=records,
            size_bytes=size,
            checksum=checksum,
            format=_file_format(path.name),
            metadata={"batch": batch} if batch else None,
        )
    return manifest.write(), manifest_hash, len(entries), size_bytes


def verify_staging(output_dir: Path | str) -> dict[str, Any]:
    root = Path(output_dir)
    manifest_path = root / MANIFEST_FILENAME
    if not manifest_path.is_file():
        raise StagingTamperedError(f"{root} has no {MANIFEST_FILENAME}")
    manifest = load_manifest(manifest_path)
    expected: dict[str, tuple[int, str, int]] = {}
    for table in manifest.get("tables", {}).values():
        for entries in table.get("formats", {}).values():
            for entry in entries:
                expected[entry["path"]] = (
                    int(entry["size_bytes"]),
                    str(entry.get("checksum")),
                    int(entry["row_count"]),
                )
    actual = {path.relative_to(root).as_posix(): path for path in _staging_files(root)}
    problems: list[str] = []
    problems.extend(f"missing {name}" for name in sorted(expected.keys() - actual.keys()))
    problems.extend(f"unlisted {name}" for name in sorted(actual.keys() - expected.keys()))
    for name in sorted(expected.keys() & actual.keys()):
        checksum, size, records = _digest_file(actual[name], is_report=name == REPORT_NAME)
        if (size, checksum, records) != expected[name]:
            problems.append(f"changed {name}")
    if problems:
        raise StagingTamperedError(
            f"DIGen staging in {root} differs from its manifest: {', '.join(problems[:10])}"
            + (f" and {len(problems) - 10} more" if len(problems) > 10 else "")
        )
    listed = sorted(
        (name, 0 if name == REPORT_NAME else size, checksum, records)
        for name, (size, checksum, records) in expected.items()
    )
    row_counts = manifest.get("source", {}).get("row_counts", {})
    if _identity(int(manifest["scale_factor"]), listed, row_counts) != manifest.get("manifest_hash"):
        raise StagingTamperedError(f"{manifest_path} does not match its manifest_hash")
    return manifest


def _result_from_manifest(
    output_dir: Path, manifest: Mapping[str, Any], seconds: float, *, reused: bool
) -> DigenResult:
    source = manifest.get("source", {})
    sizes = [
        int(entry["size_bytes"])
        for table in manifest.get("tables", {}).values()
        for entries in table.get("formats", {}).values()
        for entry in entries
    ]
    return DigenResult(
        output_dir=output_dir,
        scale_factor=int(manifest["scale_factor"]),
        manifest_path=output_dir / MANIFEST_FILENAME,
        manifest_hash=str(manifest["manifest_hash"]),
        row_counts=dict(source.get("row_counts", {})),
        digen_version=str(source.get("digen_version")),
        pdgf_version=str(source.get("pdgf_version")),
        tools_sha256=str(source.get("tools_sha256")),
        java_major=source.get("java_major"),
        java_executable=None,
        licence_notice_shown=bool(source.get("licence_notice_shown")),
        licence_notice=source.get("licence_notice"),
        file_count=len(sizes),
        size_bytes=sum(sizes),
        seconds=seconds,
        reused=reused,
    )


def _reusable_staging(output_dir: Path, scale_factor: int) -> Mapping[str, Any] | None:
    manifest_path = output_dir / MANIFEST_FILENAME
    if not manifest_path.is_file() or generation_in_progress(output_dir):
        return None
    try:
        manifest = load_manifest(manifest_path)
        if float(manifest.get("scale_factor", -1)) != float(scale_factor):
            return None
        source = manifest.get("source")
        if (
            not isinstance(source, Mapping)
            or source.get("provider") != PROVIDER
            or source.get("tools_sha256") != TOOLS_ARCHIVE_SHA256
            or source.get("data_generation_version") != DATA_GENERATION_VERSION
        ):
            return None
        return verify_staging(output_dir)
    except (OSError, ValueError, KeyError, DigenError):
        return None


def _is_digen_output(name: str) -> bool:
    return name in REQUIRED_ENTRIES or name == MANIFEST_FILENAME or name.endswith("_audit.csv")


def _prepare_output_dir(output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    children = [child for child in output_dir.iterdir() if child.name != GENERATION_IN_PROGRESS_MARKER]
    foreign = sorted(child.name for child in children if not _is_digen_output(child.name))
    if foreign:
        raise DigenOutputError(
            f"{output_dir} holds files DIGen did not write ({', '.join(foreign[:5])}); refusing to write into it"
        )
    for child in children:
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()


def _digen_command(java: JavaRuntime, scale_factor: int, output_dir: Path, environ: Mapping[str, str]) -> list[str]:
    command = [str(java.executable), "-jar", DIGEN_JAR_NAME, "-sf", str(scale_factor), "-o", str(output_dir)]
    options = environ.get(JAVA_OPTS_ENVIRONMENT, "").strip()
    if options:
        command += ["-jvm", options]
    return command


def _run_digen(command: list[str], workdir: Path) -> subprocess.CompletedProcess[Any]:
    read_end, write_end = os.pipe()
    try:
        try:
            os.write(write_end, LICENCE_ANSWER)
        finally:
            os.close(write_end)
        return run_child(
            command,
            tool=TOOL_NAME,
            deadline=current_run_deadline(),
            cwd=workdir,
            stdin=read_end,
            capture_output=True,
            text=True,
            errors="replace",
        )
    finally:
        os.close(read_end)


def generate(
    scale_factor: Any,
    output_dir: Path | str,
    *,
    environ: Mapping[str, str] | None = None,
) -> DigenResult:
    started = mono_time()
    scale = validate_digen_scale(scale_factor)
    output = Path(output_dir).resolve()
    reusable = _reusable_staging(output, scale)
    if reusable is not None:
        return _result_from_manifest(output, reusable, elapsed_seconds(started), reused=True)

    environment = os.environ if environ is None else environ
    java = find_supported_java(environment)
    notice = print_licence_notice()
    tools_dir = resolve_tools_dir()
    runs_root = tools_dir.parent.parent / "runs"
    runs_root.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="digen-", dir=runs_root))
    try:
        shutil.copytree(tools_dir, workdir / tools_dir.name)
        with track_generation(output):
            _prepare_output_dir(output)
            completed = _run_digen(_digen_command(java, scale, output, environment), workdir / tools_dir.name)
            if completed.returncode != 0:
                tail = f"{completed.stdout or ''}{completed.stderr or ''}"[-OUTPUT_TAIL_CHARACTERS:]
                raise DigenRunError(f"{TOOL_NAME} exited with status {completed.returncode}: {tail}")
            missing = [name for name in REQUIRED_ENTRIES if not (output / name).exists()]
            if missing:
                raise DigenOutputError(f"{TOOL_NAME} did not produce {', '.join(missing)} in {output}")
            report = parse_report((output / REPORT_NAME).read_text(encoding="utf-8", errors="replace"))
            if report.scale_factor != scale:
                raise DigenOutputError(
                    f"{REPORT_NAME} states scale factor {report.scale_factor}, but {scale} was requested"
                )
            manifest_path, manifest_hash, file_count, size_bytes = write_staging_manifest(
                output, report, java=java, licence_notice_shown=True, licence_notice_text=notice
            )
            verify_staging(output)
            _check_deadline()
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    return DigenResult(
        output_dir=output,
        scale_factor=scale,
        manifest_path=manifest_path,
        manifest_hash=manifest_hash,
        row_counts=report.row_counts,
        digen_version=report.digen_version,
        pdgf_version=report.pdgf_version,
        tools_sha256=TOOLS_ARCHIVE_SHA256,
        java_major=java.major,
        java_executable=str(java.executable),
        licence_notice_shown=True,
        licence_notice=notice,
        file_count=file_count,
        size_bytes=size_bytes,
        seconds=elapsed_seconds(started),
        reused=False,
    )
