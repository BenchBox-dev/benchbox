from __future__ import annotations

import hashlib
import re
from abc import abstractmethod
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Generic, Optional, TypeVar, Union

from benchbox.base import BaseBenchmark, GeneratorOutputDirMixin
from benchbox.core.connection import DatabaseConnection
from benchbox.core.operations import OperationExecutor
from benchbox.core.primitives_benchmark_utils import (
    failed_platform_error,
    quote_identifier_for_dialect,
    table_exists,
)
from benchbox.core.transactional.operations_registry_base import OperationsRegistryBase
from benchbox.core.transactional.questdb_sql import questdb_cleanup_statements, rewrite_questdb_operation_sql

ResultT = TypeVar("ResultT")
_POSTGRES_SERIES_DIALECTS = frozenset({"postgres", "postgresql"})
_SQL_ROLLBACK_AFTER_ERROR_DIALECTS = frozenset({"databricks"})
_UNNEST_GENERATE_SERIES_RE = re.compile(r"unnest\(\s*generate_series\((?P<args>[^()]*)\)\s*\)", re.IGNORECASE)
_UNNEST_SERIES_SELECT_RE = re.compile(
    r"SELECT\s+unnest\(\s*generate_series\(\s*(?P<lo>[^,()]+?)\s*,\s*(?P<hi>[^,()]+?)\s*\)\s*\)\s+AS\s+(?P<alias>\w+)",
    re.IGNORECASE,
)
_SERIES_SELECT_TEMPLATES = {
    "snowflake": "SELECT value::INT AS {alias} FROM TABLE(FLATTEN(ARRAY_GENERATE_RANGE({lo}, {hi} + 1)))",
    "bigquery": "SELECT {alias} FROM UNNEST(GENERATE_ARRAY({lo}, {hi})) AS {alias}",
    "questdb": "SELECT generate_series AS {alias} FROM generate_series({lo}, {hi})",
}
_SET_THEN_BEGIN_ISOLATION_RE = re.compile(
    r"SET\s+TRANSACTION\s+ISOLATION\s+LEVEL\s+(?P<level>REPEATABLE\s+READ|SERIALIZABLE|READ\s+COMMITTED)\s*;\s*"
    r"BEGIN\s+TRANSACTION\s*;",
    re.IGNORECASE,
)
_BEGIN_TRANSACTION_RE = re.compile(r"\bBEGIN\s+TRANSACTION\s*;", re.IGNORECASE)


def _doris_numbers_select(match: re.Match[str]) -> str:
    lo, hi = int(match.group("lo")), int(match.group("hi"))
    return f'SELECT number + {lo} AS {match.group("alias")} FROM numbers("number" = {hi - lo + 1})'


def _sql_escape(value: Any) -> str:
    return str(value).replace("'", "''")


class TransactionalBenchmarkBase(GeneratorOutputDirMixin, BaseBenchmark, OperationExecutor, Generic[ResultT]):
    _benchmark_label: str
    _staging_tables: dict[str, Any]

    operations_manager: OperationsRegistryBase[Any]
    data_generator: Any
    tables: dict[str, Path]
    _setup_dialect: str = "standard"

    @abstractmethod
    def setup(
        self,
        connection: DatabaseConnection,
        force: bool = False,
        dialect: str = "standard",
    ) -> dict[str, Any]:
        pass

    @abstractmethod
    def is_setup(self, connection: DatabaseConnection) -> bool:
        pass

    DATA_SOURCE_BENCHMARK = "tpch"

    def generate_data(self, tables: Optional[list[str]] = None) -> list[Union[str, Path]]:
        self.log_verbose(f"Generating {self._benchmark_label} data at scale factor {self.scale_factor}...")
        self.tables = self.data_generator.generate()
        self.log_verbose(f"Base TPC-H data available: {len(self.tables)} tables")
        return list(self.tables.values())

    def ensure_auxiliary_data_files(self) -> None:
        self.log_verbose("Checking for auxiliary data files (bulk load files)...")

        bulk_files_exist = self.data_generator.check_bulk_load_files_exist()

        if not bulk_files_exist:
            self.log_verbose("Bulk load files missing - generating now...")

            if self.data_generator._acquire_bulk_load_lock(timeout=300):
                try:
                    if not self.data_generator.check_bulk_load_files_exist():
                        bulk_files = self.data_generator.generate_bulk_load_files()
                        self.log_verbose(f"✅ Generated {len(bulk_files)} bulk load files")
                    else:
                        self.log_verbose("✅ Files generated by another process")
                except Exception as e:
                    self.log_verbose(f"⚠️ Warning: Failed to generate bulk load files: {e}")
                finally:
                    self.data_generator._release_bulk_load_lock()
            else:
                self.log_verbose("⚠️ Warning: Could not acquire lock for file generation (timeout)")
        else:
            self.log_verbose("✅ Bulk load files already exist")

    def get_all_operations(self) -> dict[str, Any]:
        return self.operations_manager.get_all_operations()

    def get_operation_categories(self) -> list[str]:
        return self.operations_manager.get_operation_categories()

    def get_operation(self, operation_id: str) -> Any:
        return self.operations_manager.get_operation(operation_id)

    def get_operations_by_category(self, category: str) -> dict[str, Any]:
        return self.operations_manager.get_operations_by_category(category)

    def get_benchmark_info(self) -> dict[str, Any]:
        return {
            "name": self._name,
            "version": self._version,
            "description": self._description,
            "scale_factor": self.scale_factor,
            "total_operations": self.operations_manager.get_operation_count(),
            "categories": self.get_operation_categories(),
            "tables": list(self._staging_tables.keys()),
            "data_source": "tpch",
        }

    def get_query(self, query_id: Union[int, str], **kwargs: Any) -> str:
        operation = self.operations_manager.get_operation(str(query_id))
        return operation.write_sql

    def get_queries(self, dialect: Optional[str] = None) -> dict[str, str]:
        operations = self.operations_manager.get_all_operations()
        return {op_id: op.write_sql for op_id, op in operations.items()}

    def get_queries_by_category(self, category: str) -> dict[str, str]:
        operations = self.operations_manager.get_operations_by_category(category)
        return {op_id: op.write_sql for op_id, op in operations.items()}

    def _prepare_operation(
        self,
        operation_id: str,
        connection: DatabaseConnection,
        **kwargs: Any,
    ) -> tuple[Any, Optional[str], Optional[str]]:
        if not connection:
            raise ValueError("Connection is None")
        if not hasattr(connection, "execute"):
            raise ValueError(f"Invalid connection type: {type(connection).__name__}")

        platform_key: Optional[str] = kwargs.get("platform_key")
        fallback_key: Optional[str] = kwargs.get("platform_fallback_key")
        sql_override: Optional[str] = kwargs.get("sql_override")

        operation = self.operations_manager.get_operation(operation_id)

        if platform_key:
            self._setup_dialect = platform_key
        if operation.requires_setup and not self.is_setup(connection):
            self.log_verbose("Staging tables not initialized - running setup() automatically...")
            try:
                self.setup(connection, force=False, dialect=platform_key or "standard")
                self.log_verbose("Setup completed successfully")
            except Exception as e:
                self._rollback_connection_after_error(connection)
                raise RuntimeError(f"Failed to initialize staging tables before executing '{operation_id}': {e}") from e

        if (platform_key or "").lower() == "sqlite":
            connection.commit()

        return operation, platform_key, fallback_key, sql_override

    @staticmethod
    def _lookup_platform_override(
        overrides: dict[str, Any] | None,
        platform_key: str | None,
        fallback_key: str | None = None,
    ) -> tuple[bool, Any]:
        if overrides:
            if platform_key and platform_key in overrides:
                return True, overrides[platform_key]
            if fallback_key and fallback_key in overrides:
                return True, overrides[fallback_key]
        return False, None

    def _rewrite_transactional_sql_for_platform(self, sql: str, platform_key: str | None) -> str:
        dialect = (platform_key or "").lower()
        if dialect == "doris":
            sql = _UNNEST_SERIES_SELECT_RE.sub(_doris_numbers_select, sql)
            return _BEGIN_TRANSACTION_RE.sub("BEGIN;", sql)
        template = _SERIES_SELECT_TEMPLATES.get(dialect)
        if template is not None:
            sql = _UNNEST_SERIES_SELECT_RE.sub(
                lambda m: template.format(lo=m.group("lo"), hi=m.group("hi"), alias=m.group("alias")), sql
            )
            return rewrite_questdb_operation_sql(sql) if dialect == "questdb" else sql
        if dialect not in _POSTGRES_SERIES_DIALECTS:
            return sql
        sql = _UNNEST_GENERATE_SERIES_RE.sub(r"generate_series(\g<args>)", sql)
        return _SET_THEN_BEGIN_ISOLATION_RE.sub(r"COMMIT;\nBEGIN TRANSACTION ISOLATION LEVEL \g<level>;", sql)

    def _execute_cleanup_sql(self, connection: DatabaseConnection, cleanup_sql: str, platform_key: str | None) -> None:
        if (platform_key or "").lower() == "questdb":
            statements = questdb_cleanup_statements(rewrite_questdb_operation_sql(cleanup_sql))
        else:
            statements = [cleanup_sql]
        for statement in statements:
            cleanup_res = connection.execute(statement)
            if (cleanup_err := failed_platform_error(cleanup_res)) is not None:
                raise RuntimeError(cleanup_err)

    def _rollback_connection_after_error(self, connection: DatabaseConnection) -> None:
        try:
            if hasattr(connection, "rollback"):
                connection.rollback()
        except Exception as exc:
            self.log_verbose(f"Warning: rollback after operation error failed: {exc}")
        if (getattr(self, "_setup_dialect", None) or "").lower() in _SQL_ROLLBACK_AFTER_ERROR_DIALECTS:
            try:
                connection.execute("ROLLBACK")
            except Exception as exc:
                self.log_verbose(f"SQL ROLLBACK after operation error was not needed or failed: {exc}")

    _STAGING_MANIFEST_TABLE = "benchbox_staging_manifest_v3"

    _LEGACY_STAGING_MANIFEST_TABLES: tuple[str, ...] = (
        "benchbox_staging_manifest_v2",
        "benchbox_staging_manifest",
    )

    def _quote_identifier(self, identifier: str) -> str:
        return quote_identifier_for_dialect(identifier, getattr(self, "_setup_dialect", "standard"))

    def _table_exists(self, connection: DatabaseConnection, table_name: str) -> bool:
        return table_exists(connection, table_name, self.log_verbose, getattr(self, "_setup_dialect", None))

    def _drop_legacy_staging_manifests(self, connection: DatabaseConnection) -> None:
        for legacy in self._LEGACY_STAGING_MANIFEST_TABLES:
            try:
                connection.execute(f"DROP TABLE IF EXISTS {self._quote_identifier(legacy)}")
            except Exception:
                pass

    def _staging_provenance_key(self) -> tuple[str, str, str]:
        benchmark_id = getattr(self, "_benchmark_label", self.__class__.__name__)
        try:
            scale = str(float(self.scale_factor))
        except (TypeError, ValueError):
            scale = str(self.scale_factor)
        return str(benchmark_id), scale, str(getattr(self, "_version", "unknown"))

    def _staging_source_digest(self, connection: DatabaseConnection, source_tables: list[str]) -> str:
        parts = []
        for table in source_tables:
            try:
                quoted = self._quote_identifier(table)
                res = connection.execute(f"SELECT COUNT(*) FROM {quoted}")
                if failed_platform_error(res) is not None:
                    count = 0
                else:
                    result = res.fetchone()
                    count = result[0] if result else 0
            except Exception:
                count = 0
            parts.append(f"{table}:{count}")
        payload = "|".join(parts)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def _manifest_text_type(self) -> str:
        dialect = (getattr(self, "_setup_dialect", None) or "standard").lower()
        if dialect in ("databricks", "bigquery"):
            return "STRING"
        return "TEXT" if dialect == "singlestore" else "VARCHAR"

    def _ensure_staging_manifest_table(self, connection: DatabaseConnection) -> None:
        quoted_table = self._quote_identifier(self._STAGING_MANIFEST_TABLE)
        text_type = self._manifest_text_type()
        res = connection.execute(
            f"CREATE TABLE IF NOT EXISTS {quoted_table} ("
            f"benchmark {text_type}, scale {text_type}, spec_version {text_type}, "
            f"source_digest {text_type}, created_at {text_type})"
        )
        if (err := failed_platform_error(res)) is not None:
            raise RuntimeError(f"Failed to create staging manifest table: {err}")

    def _delete_staging_manifest_entry(self, connection: DatabaseConnection, benchmark_id: str) -> Any:
        quoted_table = self._quote_identifier(self._STAGING_MANIFEST_TABLE)
        if (getattr(self, "_setup_dialect", None) or "").lower() == "questdb":
            return connection.execute(f"TRUNCATE TABLE {quoted_table}")
        return connection.execute(f"DELETE FROM {quoted_table} WHERE benchmark = '{_sql_escape(benchmark_id)}'")

    def _write_staging_manifest(self, connection: DatabaseConnection, source_tables: list[str]) -> None:
        benchmark_id, scale, spec_version = self._staging_provenance_key()
        source_digest = self._staging_source_digest(connection, source_tables)
        quoted_table = self._quote_identifier(self._STAGING_MANIFEST_TABLE)

        self._ensure_staging_manifest_table(connection)

        res2 = self._delete_staging_manifest_entry(connection, benchmark_id)
        if (err := failed_platform_error(res2)) is not None:
            raise RuntimeError(f"Failed to delete previous staging manifest entry: {err}")

        created_at = datetime.now(timezone.utc).isoformat()
        res3 = connection.execute(
            f"INSERT INTO {quoted_table} (benchmark, scale, spec_version, source_digest, created_at) VALUES "
            f"('{_sql_escape(benchmark_id)}', '{_sql_escape(scale)}', '{_sql_escape(spec_version)}', "
            f"'{_sql_escape(source_digest)}', '{_sql_escape(created_at)}')"
        )
        if (err := failed_platform_error(res3)) is not None:
            raise RuntimeError(f"Failed to insert staging manifest entry: {err}")

    def _invalidate_staging_manifest(self, connection: DatabaseConnection) -> None:
        benchmark_id, _scale, _spec = self._staging_provenance_key()
        try:
            self._delete_staging_manifest_entry(connection, benchmark_id)
        except Exception as e:
            self.log_verbose(f"Staging manifest not cleared ({e})")

    def _staging_manifest_matches(self, connection: DatabaseConnection, source_tables: list[str]) -> bool:
        benchmark_id, scale, spec_version = self._staging_provenance_key()
        source_digest = self._staging_source_digest(connection, source_tables)
        quoted_table = self._quote_identifier(self._STAGING_MANIFEST_TABLE)
        try:
            if not self._table_exists(connection, self._STAGING_MANIFEST_TABLE):
                return False
            query = (
                f"SELECT COUNT(*) FROM {quoted_table} WHERE "
                f"benchmark = '{_sql_escape(benchmark_id)}' AND "
                f"scale = '{_sql_escape(scale)}' AND "
                f"spec_version = '{_sql_escape(spec_version)}' AND "
                f"source_digest = '{_sql_escape(source_digest)}'"
            )
            res = connection.execute(query)
            if failed_platform_error(res) is not None:
                return False
            result = res.fetchone()
            return bool(result and result[0])
        except Exception:
            return False

    def run_benchmark(
        self,
        connection: DatabaseConnection,
        operation_ids: Optional[list[str]] = None,
        categories: Optional[list[str]] = None,
    ) -> list[ResultT]:
        if operation_ids:
            operations = {op_id: self.get_operation(op_id) for op_id in operation_ids}
        elif categories:
            operations = {}
            for category in categories:
                operations.update(self.get_operations_by_category(category))
        else:
            operations = self.get_all_operations()

        self.log_verbose(f"Running {len(operations)} write operations...")

        results: list[ResultT] = []
        for op_id in operations:
            result = self.execute_operation(op_id, connection)
            results.append(result)

            status = "✓" if result.success and result.validation_passed else "✗"
            self.log_verbose(
                f"{status} {op_id}: {result.write_duration_ms:.2f}ms write, "
                f"{result.validation_duration_ms:.2f}ms validation"
            )

        return results
