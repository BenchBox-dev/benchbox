@pytest.mark.parametrize("damage", ["change", "delete", "add", "report"])
def test_tampered_staging_is_refused(
    tmp_path: Path, tools_dir: Path, environment: dict[str, str], child: Child, damage: str
) -> None:
    out = tmp_path / "out"
    digen.generate(3, out, environ=environment)
    root = out.resolve()
    if damage == "change":
        (root / "Batch1" / "DailyMarket.txt").write_text("tampered\n")
        expected = "changed Batch1/DailyMarket.txt"
    elif damage == "delete":
        (root / "Batch3" / "DailyMarket.txt").unlink()
        expected = "missing Batch3/DailyMarket.txt"
    elif damage == "add":
        (root / "Batch2" / "Extra.txt").write_text("x\n")
        expected = "unlisted Batch2/Extra.txt"
    else:
        report = root / digen.REPORT_NAME
        report.write_text(report.read_text(encoding="utf-8").replace("Batch2: 20", "Batch2: 21"))
        expected = f"changed {digen.REPORT_NAME}"
    with pytest.raises(digen.StagingTamperedError, match=expected):
        digen.verify_staging(root)


