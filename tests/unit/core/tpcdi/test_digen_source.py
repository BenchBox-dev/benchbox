@pytest.mark.skipif(
    os.name == "nt", reason="the stub records its shell pid and the test probes it with os.kill(pid, 0)"
)
def test_run_time_limit_ends_the_child_and_the_ended_generation_is_not_reused(tmp_path: Path, tools_dir: Path) -> None:
    pid_file = tmp_path / "child.pid"
    home = tmp_path / "slowjdk"
    write_java_stub(
        home,
        'if [ "$1" = "-version" ]; then echo \'openjdk version "1.8.0_1"\' >&2; exit 0; fi\n'
        f"echo $$ > {pid_file}\nexec sleep 60\n",
        "",
    )
    out = tmp_path / "out"
    environ = {"JAVA_HOME": str(home), "PATH": ""}

    started = time.monotonic()
    with own_run_deadline(1):
        with pytest.raises(RunTimeoutError) as excinfo:
            digen.generate(3, out, environ=environ)
    assert time.monotonic() - started < 30
    assert "BenchBox stopped DIGen" in str(excinfo.value)

    pid = int(pid_file.read_text(encoding="utf-8"))
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            break
        time.sleep(0.1)
    with pytest.raises(ProcessLookupError):
        os.kill(pid, 0)
    assert (out / GENERATION_IN_PROGRESS_MARKER).exists()
    assert not (out / MANIFEST_FILENAME).exists()
    assert digen._reusable_staging(out.resolve(), 3) is None


