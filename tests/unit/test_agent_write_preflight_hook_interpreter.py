from __future__ import annotations

import os
import shlex
import subprocess
import sys
from pathlib import Path

import pytest

from tests.utilities.paths import REPO_ROOT
from tests.utilities.posix_shell import run_posix_shell, skip_without_posix_shell

pytestmark = [
    pytest.mark.unit,
    pytest.mark.fast,
]

SCRIPT = REPO_ROOT / "scripts" / "agent_write_preflight.sh"

HUMAN_IDENTITY = {
    "GIT_AUTHOR_NAME": "Joe Harris",
    "GIT_AUTHOR_EMAIL": "joeharris76@gmail.com",
}


def _linked_worktree(tmp_path: Path) -> tuple[Path, Path]:
    primary = tmp_path / "BenchBox"
    primary.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=primary, check=True)
    subprocess.run(["git", "config", "user.name", "BenchBox Test"], cwd=primary, check=True)
    subprocess.run(["git", "config", "user.email", "test@example.com"], cwd=primary, check=True)
    (primary / "README.md").write_text("fixture\n", encoding="utf-8")
    subprocess.run(["git", "add", "README.md"], cwd=primary, check=True)
    subprocess.run(["git", "commit", "-qm", "initial"], cwd=primary, check=True)
    linked = tmp_path / "BenchBox.wt-hooks"
    subprocess.run(
        ["git", "worktree", "add", "-q", "-b", "fix/hook-health", str(linked), "HEAD"], cwd=primary, check=True
    )
    return primary, linked


def _write_generated_hook(primary: Path, interpreter_line: str) -> None:
    hooks = primary / ".git" / "hooks"
    hooks.mkdir(parents=True, exist_ok=True)
    hook = hooks / "pre-commit"
    hook.write_text(
        "#!/usr/bin/env bash\n"
        "# File generated by pre-commit: https://pre-commit.com\n"
        "# start templated\n"
        f"INSTALL_PYTHON={interpreter_line}\n"
        "# end templated\n",
        encoding="utf-8",
    )
    hook.chmod(0o755)


def _preflight(tmp_path: Path, interpreter_line: str) -> subprocess.CompletedProcess[str]:
    skip_without_posix_shell()
    primary, linked = _linked_worktree(tmp_path)
    _write_generated_hook(primary, interpreter_line)
    env = {**os.environ, **HUMAN_IDENTITY}
    for name in ("BENCHBOX_AGENT_PRIMARY_CLONE", "BENCHBOX_ALLOW_MAIN_CLONE_WRITE", "ALLOW_MAIN_CLONE_WRITE"):
        env.pop(name, None)
    env.pop("BENCHBOX_EPHEMERAL_CLONE", None)
    return run_posix_shell(
        f"sh {shlex.quote(SCRIPT.as_posix())}",
        cwd=linked,
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )


def _executable_with_a_space(tmp_path: Path) -> Path:
    interpreter = tmp_path / "python home" / "python"
    interpreter.parent.mkdir()
    interpreter.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    interpreter.chmod(0o755)
    return interpreter


def test_an_unquoted_interpreter_path_is_accepted(tmp_path: Path) -> None:
    result = _preflight(tmp_path, sys.executable)

    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize("quote", ["'", '"'])
def test_a_quoted_interpreter_path_is_accepted(tmp_path: Path, quote: str) -> None:
    result = _preflight(tmp_path, f"{quote}{sys.executable}{quote}")

    assert result.returncode == 0, result.stdout + result.stderr


def test_a_single_quoted_interpreter_path_containing_a_space_is_accepted(tmp_path: Path) -> None:
    interpreter = _executable_with_a_space(tmp_path)

    result = _preflight(tmp_path, shlex.quote(str(interpreter)))

    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize("quote", ["", "'", '"'])
def test_a_missing_interpreter_is_still_refused(tmp_path: Path, quote: str) -> None:
    missing = tmp_path / "BenchBox.wt-deleted" / ".venv" / "bin" / "python"

    result = _preflight(tmp_path, f"{quote}{missing}{quote}")

    assert result.returncode == 1
    assert "shared pre-commit hook is not usable" in result.stderr
    assert str(missing) in result.stderr


@pytest.mark.parametrize("quote", ["", "'"])
def test_a_non_executable_interpreter_is_still_refused(tmp_path: Path, quote: str) -> None:
    interpreter = _executable_with_a_space(tmp_path)
    interpreter.chmod(0o644)

    result = _preflight(tmp_path, f"{quote}{interpreter}{quote}" if quote else shlex.quote(str(interpreter)))

    assert result.returncode == 1
    assert "shared pre-commit hook is not usable" in result.stderr
